/**
 * The demo market: 30 venues across six cities.
 *
 * ── Why fixtures at all ─────────────────────────────────────────────────────
 * The frontend is being built before the multi-tenant API is finished, and a UI
 * that can only be judged with Postgres and Redis running is a UI nobody reviews.
 * These shapes deliberately mirror what the real endpoints already return —
 * `demand`, `remaining` and `slots[].scarce` come from availability.service.js,
 * `bookingType`/`prepaid` from the reservation rules payload, `headroom` from the
 * overbooking service — so services/marketplace.js can swap fixtures for HTTP
 * without a single component changing.
 *
 * ── Why the compact notation ────────────────────────────────────────────────
 * `slots: '19:15 20:00* 21:45!'` and `tables: '4x2 6x4 1x8'` instead of nested
 * object literals. Thirty venues authored longhand is 1,500 lines nobody will
 * read or keep consistent; in this form a venue is legible at a glance and the
 * parsers below are the only place the shape is known.
 *
 *   slots   `HH:MM`  ·  `*` best match for the searched time  ·  `!` last table
 *   tables  `count x seats`, distributed across the venue's zones
 *
 * All names are invented. Areas are real, so distances and neighbourhood filters
 * behave believably.
 */

