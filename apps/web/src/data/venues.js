/* ═══════════════════════════════════════════════════════════════ parsers ══ */

/** `'19:15 20:00* 21:45!'` → `[{ time, best, scarce }]` */
function parseSlots(spec) {
  if (!spec) return [];
  return spec
    .trim()
    .split(/\s+/)
    .map((token) => ({
      time: token.replace(/[*!]/g, ''),
      best: token.includes('*'),
      scarce: token.includes('!'),
    }));
}

/**
 * `'4x2 6x4 1x8'` → 11 labelled tables.
 *
 * Zones are dealt out largest-table-first so the biggest tables land in MAIN or
 * PRIVATE rather than at the bar, which is how a floor plan actually works. The
 * labels (`T1`, `B2`, `P1`) are what the console's floor view and the assignment
 * algorithm both display, so they have to be stable — hence generated from the
 * spec order, not shuffled.
 */
function parseTables(spec, zones) {
  const groups = spec
    .trim()
    .split(/\s+/)
    .map((token) => {
      const [count, seats] = token.split('x').map(Number);
      return { count, seats };
    })
    .sort((a, b) => b.seats - a.seats);

  const zonePrefix = { MAIN: 'T', OUTDOOR: 'O', BAR: 'B', BOOTH: 'D', COUNTER: 'C', PRIVATE: 'P' };
  const counters = {};
  const tables = [];
  let zoneIndex = 0;

  for (const group of groups) {
    for (let i = 0; i < group.count; i += 1) {
      // Big tables prefer the front of the zone list (MAIN/PRIVATE are authored
      // first); everything else round-robins so no zone ends up empty.
      const zone = group.seats >= 8 ? zones[0] : zones[zoneIndex++ % zones.length];
      counters[zone] = (counters[zone] ?? 0) + 1;
      tables.push({
        id: `${zone}-${counters[zone]}`,
        label: `${zonePrefix[zone] ?? 'T'}${counters[zone]}`,
        seats: group.seats,
        zone,
      });
    }
  }

  return tables;
}

/**
 * Booking policy, derived from the venue's type with per-type reasoning:
 *
 *  - experiences are prepaid, so cancellation has to be far enough out that the
 *    kitchen can resell the seat — 48 hours, and the deposit is the ticket;
 *  - counters have almost no slack (one seat is 8% of the room) so the grace
 *    period is short and honest about it;
 *  - waitlist venues take no bookings at all, so only the hold matters.
 */
function policyFor(v) {
  const base = { holdMinutes: 5, cancelHours: 4, graceMinutes: 15, depositPaise: null, largePartyFrom: 7 };

  if (v.type === 'experience') {
    return { ...base, cancelHours: 48, graceMinutes: 10, depositPaise: v.prepaid ?? null };
  }
  if (v.type === 'counter') return { ...base, cancelHours: 12, graceMinutes: 10 };
  if (v.type === 'waitlist') return { ...base, cancelHours: 0, graceMinutes: 10 };
  return base;
}

/** Deterministic per-venue extras that would be columns in the real schema. */
function derive(v) {
  const random = rng(v.slug);
  const tables = parseTables(v.tables, v.zones);
  const seats = tables.reduce((sum, t) => sum + t.seats, 0);
  const slots = parseSlots(v.slots);

  return {
    ...v,
    id: v.slug,
    tables,
    seats,
    slots,
    prepaid: v.prepaid ?? null,
    curated: v.curated ?? null,
    walkIn: v.walkIn ?? false,
    /** Largest party a single table takes — drives the "fits 6+" filter. */
    maxTableSeats: Math.max(...tables.map((t) => t.seats)),
    /** Spare covers the overbooking service says this venue could still sell. */
    headroom: Math.round(seats * (1 - v.demand)),
    hue: seedHue(v.slug),
    image: v.image ?? venueImage(v.slug),
    imageSrcSet: v.imageSrcSet ?? venueImageSrcSet(v.slug),
    phone: `+91 ${random.int(20, 99)} ${random.int(2000, 9999)} ${random.int(1000, 9999)}`,
    hours: v.price >= 3 ? { open: '18:00', close: '23:30' } : { open: '11:30', close: '23:00' },
    policy: policyFor(v),
    /** 30-day booking volume — used by the console and the "busy" signals. */
    monthlyBookings: Math.round(seats * random.float(11, 26)),
  };
}

export const VENUES = AUTHORED.map(derive);

export function getVenue(slug) {
  return VENUES.find((v) => v.slug === slug) ?? null;
}

export function venuesInCity(citySlug) {
  return VENUES.filter((v) => v.city === citySlug);
}

